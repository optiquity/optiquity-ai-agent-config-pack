per_entry_regenerate_index() {
    local key="$1"
    local stream_dir="$2"

    [[ -n "$key" ]] || pe_die "per_entry_regenerate_index: stream key required"
    [[ -n "$stream_dir" ]] || \
        pe_die "per_entry_regenerate_index: stream dir required"

    # Only the impl-plan stream carries `_index.md`. Any other stream is a
    # caller error (backlog is unordered → no index).
    if [[ "$key" != "$PE_INDEX_STREAM" ]]; then
        pe_die "per_entry_regenerate_index: only $PE_INDEX_STREAM carries _index.md (got: $key)"
    fi
    [[ -d "$stream_dir" ]] || \
        pe_die "per_entry_regenerate_index: stream dir not found: $stream_dir"

    local index_path="$stream_dir/_index.md"
    local index_tmp
    index_tmp=$(mktemp "$stream_dir/.per-entry-index.XXXXXX") || \
        pe_die "per_entry_regenerate_index: mktemp failed"
    # shellcheck disable=SC2064
    trap "rm -f '$index_tmp'" EXIT

    pe__index_python "$stream_dir" "$index_tmp" generate || \
        pe_die "per_entry_regenerate_index: python generator failed"

    # Idempotency: leave an unchanged on-disk file untouched (no mtime churn).
    if [[ -f "$index_path" ]] && cmp -s "$index_tmp" "$index_path"; then
        rm -f "$index_tmp"
        trap - EXIT
        return 0
    fi

    mv "$index_tmp" "$index_path"
    trap - EXIT
    return 0
}

per_entry_validate_index() {
    local key="$1"
    local stream_dir="$2"

    [[ -n "$key" ]] || pe_die "per_entry_validate_index: stream key required"
    [[ -n "$stream_dir" ]] || \
        pe_die "per_entry_validate_index: stream dir required"

    # SKIP-lenient for non-impl-plan streams + absent directories.
    if [[ "$key" != "$PE_INDEX_STREAM" ]]; then
        return 0
    fi
    if [[ ! -d "$stream_dir" ]]; then
        return 0
    fi

    local out
    if out=$(pe__index_python "$stream_dir" "" validate); then
        echo "[index-validate] PASS — _index.md order is a valid topological order of the rule-based deps + membership matches the tree."
        return 0
    fi
    echo "[index-validate] FAIL — _index.md violates a hard property:" >&2
    printf '%s\n' "$out" | while IFS= read -r line; do
        [[ -n "$line" ]] && echo "  - $line" >&2
    done
    return 1
}
